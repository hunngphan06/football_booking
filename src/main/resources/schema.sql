SELECT seed.code, seed.name
FROM (VALUES ('SPORTS', 'Bóng đá'), ('CINEMA', 'Phim'), ('MUSIC', 'Ca nhạc')) AS seed(code, name)
WHERE NOT EXISTS (SELECT 1 FROM app_migrations WHERE name = 'event_category_seed')
  AND NOT EXISTS (SELECT 1 FROM event_categories WHERE code = seed.code)
ON CONFLICT DO NOTHING;

INSERT INTO app_migrations (name)
SELECT 'event_category_seed'
WHERE NOT EXISTS (SELECT 1 FROM app_migrations WHERE name = 'event_category_seed')
ON CONFLICT DO NOTHING;

