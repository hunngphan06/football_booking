CREATE TABLE IF NOT EXISTS ticket_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES events (id),
    name VARCHAR(255) NOT NULL,
    price NUMERIC(14, 2) NOT NULL CHECK (price >= 0),
    total_quantity INTEGER NOT NULL CHECK (total_quantity > 0)
);

CREATE INDEX IF NOT EXISTS idx_ticket_types_match_id ON ticket_types (match_id);

ALTER TABLE ticket_types ADD COLUMN IF NOT EXISTS allocated_quantity INTEGER DEFAULT 0 NOT NULL
    CHECK (allocated_quantity >= 0 AND allocated_quantity <= total_quantity);

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(36) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers (id),
    match_id BIGINT NOT NULL REFERENCES events (id),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'PAID', 'CONFIRMED', 'CANCELLED')),
    total_amount NUMERIC(30, 2) NOT NULL CHECK (total_amount >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS booking_items (
    booking_id BIGINT NOT NULL REFERENCES bookings (id),
    ticket_type_id BIGINT NOT NULL REFERENCES ticket_types (id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(14, 2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (booking_id, ticket_type_id)
);

CREATE INDEX IF NOT EXISTS idx_bookings_event ON bookings (match_id);
CREATE INDEX IF NOT EXISTS idx_bookings_customer_id ON bookings (customer_id, id);

CREATE TABLE IF NOT EXISTS payments (
    booking_id BIGINT PRIMARY KEY REFERENCES bookings (id),
    reference VARCHAR(36) NOT NULL UNIQUE,
    amount NUMERIC(30, 2) NOT NULL CHECK (amount >= 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'FAILED', 'SUCCEEDED', 'REFUND_PENDING', 'REFUNDED')),
    scenario VARCHAR(24) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    charged_at TIMESTAMP WITH TIME ZONE,
    refunded_at TIMESTAMP WITH TIME ZONE
);

INSERT INTO payments (booking_id, reference, amount, status, scenario, created_at, updated_at, charged_at)
SELECT id, reference, total_amount, 'SUCCEEDED', 'SUCCESS', paid_at, paid_at, paid_at
FROM bookings
WHERE paid_at IS NOT NULL AND NOT EXISTS (SELECT 1 FROM payments WHERE booking_id = bookings.id)
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS booking_accounts (
    email VARCHAR(255) PRIMARY KEY,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(12) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    customer_id BIGINT UNIQUE REFERENCES customers (id),
    CHECK ((role = 'USER' AND customer_id IS NOT NULL) OR (role = 'ADMIN' AND customer_id IS NULL))
);
