CREATE TABLE IF NOT EXISTS football_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_team VARCHAR(255) NOT NULL,
    away_team VARCHAR(255) NOT NULL,
    stadium VARCHAR(255) NOT NULL,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    description TEXT,
    organizer VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS ticket_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES football_matches (id),
    name VARCHAR(255) NOT NULL,
    price NUMERIC(14, 2) NOT NULL CHECK (price >= 0),
    total_quantity INTEGER NOT NULL CHECK (total_quantity > 0)
);

CREATE INDEX IF NOT EXISTS idx_ticket_types_match_id ON ticket_types (match_id);

ALTER TABLE ticket_types ADD COLUMN IF NOT EXISTS allocated_quantity INTEGER DEFAULT 0 NOT NULL
    CHECK (allocated_quantity >= 0 AND allocated_quantity <= total_quantity);

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(36) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers (id),
    match_id BIGINT NOT NULL REFERENCES football_matches (id),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'PAID', 'CONFIRMED', 'CANCELLED')),
    total_amount NUMERIC(30, 2) NOT NULL CHECK (total_amount >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS booking_items (
    booking_id BIGINT NOT NULL REFERENCES bookings (id),
    ticket_type_id BIGINT NOT NULL REFERENCES ticket_types (id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(14, 2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (booking_id, ticket_type_id)
);

CREATE INDEX IF NOT EXISTS idx_bookings_customer_id ON bookings (customer_id, id);
